class OneCardManager:
    """Менеджер для гадания «Одна карта»"""

    def __init__(self):
        self.cards = ONE_CARD_READINGS

    def get_random_card(self) -> Dict[str, Any]:
        """Получает случайную карту"""
        return random.choice(self.cards)

    def get_card_by_id(self, card_id: int) -> Optional[Dict[str, Any]]:
        """Получает карту по ID"""
        for card in self.cards:
            if card.get('id') == card_id:
                return card
        return None

    def get_cards_by_tag(self, tag: str) -> list:
        """Получает карты по тегу"""
        return [card for card in self.cards if tag in card.get('tags', [])]

    def get_cards_by_theme(self, theme: str) -> list:
        """Получает карты по теме (из списка тем)"""
        theme_map = {
            'love': ['любовь', 'отношения', 'сердце', 'чувства', 'романтика'],
            'career': ['работа', 'карьера', 'финансы', 'деньги', 'успех'],
            'personal': ['сила', 'уверенность', 'развитие', 'мудрость', 'решения'],
            'change': ['перемены', 'новое начало', 'трансформация', 'судьба']
        }

        keywords = theme_map.get(theme, [])
        if not keywords:
            return []

        result = []
        for card in self.cards:
            card_tags = card.get('tags', [])
            for keyword in keywords:
                if any(keyword in tag for tag in card_tags):
                    result.append(card)
                    break
        return result

    def format_message(self, card: Dict[str, Any]) -> str:
        """Форматирует сообщение для отправки пользователю"""
        return f"""{card['emoji']} <b>Ваша карта — {card['name_ru']}</b>

{card['message']}

<b>💡 Совет:</b>
{card['advice']}

<b>✨ Аффирмация:</b>
<i>{card['affirmation']}</i>

<em>Карта: {card['name_ru']} ({card['name_en']})</em>"""


def get_one_card() -> str:
    manager = OneCardManager()
    card = manager.get_random_card()

    # Формируем и отправляем сообщение
    text = manager.format_message(card)

    return text