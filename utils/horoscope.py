class DailyHoroscopeManager:
    """Менеджер для работы с ежедневными раскладами"""

    def __init__(self):
        self.horoscopes = DAILY_HOROSCOPES

    def get_today_horoscope(self, seed: Optional[int] = None) -> dict:
        """
        Получает расклад на сегодня

        Args:
            seed: Опциональный seed для детерминированного выбора

        Returns:
            dict: Расклад на сегодня
        """
        # Используем день года как seed, чтобы каждый день был разный
        day_of_year = datetime.now().timetuple().tm_yday

        if seed is not None:
            random.seed(seed)
        else:
            random.seed(day_of_year)

        # Выбираем случайный расклад
        horoscope = random.choice(self.horoscopes)

        # Сбрасываем seed
        random.seed()

        return horoscope

    def get_horoscope_by_theme(self, theme: str) -> list:
        """
        Получает расклады по теме

        Args:
            theme: Тема (love, career, health, general)

        Returns:
            list: Список раскладов по теме
        """
        return [h for h in self.horoscopes if h.get('theme') == theme]

    def get_horoscope_by_mood(self, mood: str) -> list:
        """
        Получает расклады по настроению

        Args:
            mood: Настроение (positive, neutral, serious)

        Returns:
            list: Список раскладов по настроению
        """
        return [h for h in self.horoscopes if h.get('mood') == mood]

    def get_random_horoscope(self) -> dict:
        """Получает случайный расклад"""
        return random.choice(self.horoscopes)

    def format_daily_message(self, horoscope: dict) -> str:
        """
        Форматирует расклад в сообщение для пользователя

        Args:
            horoscope: Словарь с данными расклада

        Returns:
            str: Отформатированное сообщение
        """
        return f"""
{horoscope['title']}

{horoscope['message']}

<b>💡 Совет на день:</b>
{horoscope['advice']}

<b>✨ Аффирмация дня:</b>
<i>{horoscope['affirmation']}</i>

<em>Карта дня: {horoscope['card_name_ru']} ({horoscope['orientation']})</em>
"""


async def send_daily_horoscope(bot: Bot, user_id: int):
    """
    Отправляет ежедневный расклад пользователю
    """
    horoscope_manager = DailyHoroscopeManager()
    # Получаем расклад на сегодня
    horoscope = horoscope_manager.get_today_horoscope()

    # Форматируем сообщение
    text = horoscope_manager.format_daily_message(horoscope)

    # Отправляем
    await bot.send_message(
        chat_id=user_id,
        text=text,
        parse_mode='HTML'
    )